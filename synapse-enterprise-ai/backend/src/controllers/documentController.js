import { query } from '../config/db.js';
import { analyzeDocumentWithGemini } from '../services/geminiService.js';
import { logAuditEvent } from '../services/auditService.js';

export const getDocuments = async (req, res) => {
  try {
    const { department } = req.query;
    let sql = 'SELECT * FROM documents';
    const params = [];

    // Filter if department is specified or enforce employee boundary
    if (department && department !== 'all') {
      sql += ' WHERE department = $1';
      params.push(department);
    } else if (req.user.role === 'employee') {
      // Employees are scoped to their home department
      sql += ' WHERE department = $1';
      params.push(req.user.department);
    }

    const result = await query(sql, params);
    return res.status(200).json({
      success: true,
      count: result.rows.length,
      documents: result.rows
    });
  } catch (error) {
    console.error('[Document Controller Get Error]:', error);
    return res.status(500).json({
      success: false,
      error: 'Failed to retrieve documents.'
    });
  }
};

export const getDocumentById = async (req, res) => {
  try {
    const { id } = req.params;
    const result = await query('SELECT * FROM documents WHERE id = $1', [id]);

    if (!result.rows || result.rows.length === 0) {
      return res.status(404).json({
        success: false,
        error: 'Document not found.'
      });
    }

    const doc = result.rows[0];

    // RBAC department check
    if (req.user.role === 'employee' && doc.department !== req.user.department) {
      return res.status(403).json({
        success: false,
        error: 'Access denied: You do not have permission to view documents from this department.'
      });
    }

    return res.status(200).json({
      success: true,
      document: doc
    });
  } catch (error) {
    return res.status(500).json({
      success: false,
      error: 'Failed to retrieve document details.'
    });
  }
};

export const createDocument = async (req, res) => {
  try {
    const { title, department, fileType, content } = req.body;

    console.log(`[Document Ingestion] Processing "${title}" for department "${department}" with Gemini...`);

    // Perform AI analysis and structured extraction via Gemini
    const aiAnalysis = await analyzeDocumentWithGemini({
      title,
      department,
      fileType,
      content
    });

    const summaryText = aiAnalysis.summary || 'Summary generated by Synapse Core.';
    const entitiesJson = JSON.stringify(aiAnalysis);

    const result = await query(
      `INSERT INTO documents (title, department, file_type, raw_content, ai_summary, extracted_entities, uploaded_by)
       VALUES ($1, $2, $3, $4, $5, $6, $7)
       RETURNING *`,
      [title, department, fileType, content, summaryText, entitiesJson, req.user.id]
    );

    const savedDoc = result.rows[0];

    await logAuditEvent(req.user.id, 'INGEST_DOCUMENT', {
      documentId: savedDoc.id,
      title: savedDoc.title,
      department: savedDoc.department,
      fileType: savedDoc.file_type,
      sentiment: aiAnalysis.sentiment
    });

    return res.status(201).json({
      success: true,
      message: 'Document successfully ingested and analyzed by Google Gemini.',
      document: savedDoc,
      extraction: aiAnalysis
    });
  } catch (error) {
    console.error('[Document Controller Create Error]:', error);
    return res.status(500).json({
      success: false,
      error: 'Failed to ingest and analyze document with Gemini.'
    });
  }
};

export const deleteDocument = async (req, res) => {
  try {
    const { id } = req.params;

    // Check existence
    const existing = await query('SELECT * FROM documents WHERE id = $1', [id]);
    if (!existing.rows || existing.rows.length === 0) {
      return res.status(404).json({
        success: false,
        error: 'Document not found.'
      });
    }

    const doc = existing.rows[0];

    // Only Admin or Manager of that department can delete
    if (req.user.role === 'employee' || (req.user.role === 'manager' && req.user.department !== doc.department)) {
      return res.status(403).json({
        success: false,
        error: 'Access denied: Only Admins or Department Managers can remove documents.'
      });
    }

    await query('DELETE FROM documents WHERE id = $1', [id]);

    await logAuditEvent(req.user.id, 'DELETE_DOCUMENT', {
      documentId: id,
      title: doc.title,
      department: doc.department
    });

    return res.status(200).json({
      success: true,
      message: 'Document removed from enterprise repository.'
    });
  } catch (error) {
    return res.status(500).json({
      success: false,
      error: 'Failed to delete document.'
    });
  }
};

